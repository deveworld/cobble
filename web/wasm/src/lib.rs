const DEFAULT_NAMESPACE: &str = "cobble";

#[derive(Serialize)]
struct CompileFile {
    path: String,
    kind: String,
    content: String,
}

#[derive(Serialize)]
struct CompileSummary {
    namespace: String,
    pack_format: String,
    minecraft_version: String,
    function_count: usize,
    command_count: usize,
    resource_count: usize,
    file_count: usize,
}

#[derive(Serialize)]
struct CompilerMetadata {
    pack_format: String,
    minecraft_version: String,
}

#[derive(Clone, Debug, Serialize)]
struct CompileDiagnostic {
    file: String,
    line: usize,
    column: usize,
    severity: String,
    kind: String,
    message: String,
    help: Option<String>,
    suggested_cobble_alternative: Option<String>,
    formatted: String,
}

#[derive(Serialize)]
struct CompileResponse {
    ok: bool,
    files: Vec<CompileFile>,
    diagnostics: Vec<String>,
    diagnostic_details: Vec<CompileDiagnostic>,
    summary: CompileSummary,
    #[serde(skip_serializing_if = "Option::is_none")]
    experimental_python_compat: Option<CompilePythonCompatReport>,
}

#[derive(Serialize)]
struct CompilePythonCompatReport {
    enabled: bool,
    mode: String,
    supported_constructs: Vec<String>,
    observed_constructs: Vec<String>,
    unsupported_detected: Vec<CompileDiagnostic>,
}

